export const DEFAULT_ROUTE_STATS: { distanceKm: number; durationMinutes: number } = {
  distanceKm: 13.3,
  durationMinutes: 26,
};

/**
 * Fetch the fastest driving route following real streets and roads between stops
 */
export async function fetchFastestRoadRoute(
  stops: RoadCoord[]
): Promise<RouteRoadResult> {
  if (!stops || stops.length < 2) {
    return {
      coordinates: DEFAULT_ROAD_COORDINATES,
      distanceKm: DEFAULT_ROUTE_STATS.distanceKm,
      durationMinutes: DEFAULT_ROUTE_STATS.durationMinutes,
    };
  }

  try {
    const coordString = stops.map((s) => `${s.lng.toFixed(5)},${s.lat.toFixed(5)}`).join(';');
    const url = `https://router.project-osrm.org/route/v1/driving/${coordString}?overview=full&geometries=geojson`;

    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 6000);

    const response = await fetch(url, {
      signal: controller.signal,
      headers: { 'User-Agent': 'BinMatrixMobile/1.0' },
    });
    clearTimeout(timeout);

    if (!response.ok) {
      throw new Error(`Routing API error: ${response.status}`);
    }

    const data = await response.json();
    if (data.code === 'Ok' && data.routes && data.routes.length > 0) {
      const route = data.routes[0];
      const coordinates: RoadCoord[] = route.geometry.coordinates.map(
        (c: [number, number]) => ({
          lat: Number(c[1].toFixed(5)),
          lng: Number(c[0].toFixed(5)),
        })
      );

      return {
        coordinates,
        distanceKm: Number((route.distance / 1000).toFixed(1)),
        durationMinutes: Math.round(route.duration / 60),
      };
    }
  } catch {
    // Fall back gracefully to precomputed road route
  }

  return {
    coordinates: DEFAULT_ROAD_COORDINATES,
    distanceKm: DEFAULT_ROUTE_STATS.distanceKm,
    durationMinutes: DEFAULT_ROUTE_STATS.durationMinutes,
  };
}
